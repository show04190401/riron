"""VOICEVOX の読み間違いを直す（音声を作るときだけ使う。アプリの文・ハッシュは変えない）。

読みの点検：audit.py で、区切りの文を形態素に分けて読みを一覧にし、まちがっているものをここに足す。
"""
import re

FIX = {
    "all": [
        (r"(?<!平)等(?!し)", "とう"),             # 公益法人等または・資産等及び → ひとし（×）。等しい・平等はそのまま
        (r"年(?=[0-9０-９])", "ねん"),            # 年800万円 → とし800万円（×）
        (r"行っ(?=[てた])", "おこなっ"),          # 行っている → いっている（×）
        (r"帰せられ", "きせられ"),                # かえせられ（×）
        (r"責め(?=に)", "せめ"),                  # ぜめ（×）
        (r"賦払", "ふばらい"),                    # ぶばらい（×）
        (r"設備投資", "せつびとうし"),            # せつびとおし（×）
        (r"申出", "もうしで"),                    # さる（×）
        (r"署長等", "署長とう"),                  # ながら（×）
        (r"納期限", "のうきげん"),                # おさめきげん（×）
        (r"既償却", "きしょうきゃく"),            # すんでしょうきゃく（×）
        (r"外貨建", "がいかだて"),                # がいかけん（×）
        (r"建\s*ぶつ", "たてもの"),               # 建物 → けんぶつ（×）
        (r"物損", "ぶっそん"),                    # ものそん（×）
        (r"つき次", "つきつぎ"),                  # つきなみ（×）
        (r"基通([^\s、。]+?)ひく([^\s、。]+)", r"きつう\1の\2"),  # 基通九ひく六 → きつう九の六
        (r"(?<![一-龥])([一-龥])[ 　]+([一-龥])(?![一-龥])", r"\1\2"),  # 「原　則」「法　人」など字を空けた見出し → はら すなわち（×）
        (r"行(?=[うわいえお])", "おこな"),        # 行うえきむ → くだり（×）
        (r"前々日", "ぜんぜんじつ"),
        (r"前々", "ぜんぜん"),                    # 前々事業年度 → まえまえ（×）
        (r"^中(?=に)", "ちゅう"),                 # （期間）中に → なかに（×）
        (r"金地金", "きんじがね"),
        (r"積込", "つみこみ"),                    # せきこみ（×）
        (r"国貨\s*ぶつ", "国かもつ"),             # 内国貨物 → うち こっか ぶつ（×）
        (r"貨\s*ぶつ", "かもつ"),
        (r"届出", "とどけで"),                    # とどけいで（×）
        (r"引取", "ひきとり"),                    # ひきと（×）
        (r"船用品", "せんようひん"),              # ふねようひん（×）
        (r"日当", "にっとう"),                    # ひなた（×）
        (r"だ後", "だあと"),                      # やんだ後 → やんだこう（×）
        (r"譲受", "ゆずりうけ"),                  # 譲受法人・低額譲受 → じょうじゅ（×）
        (r"とう内", "とうない"),                  # 三親等内 → さんしんとううち（×）
        (r"転出とう", "てんしゅつとう"),
        (r"弁識", "べんしき"),                    # わきまえしき（×）
        (r"代襲", "だいしゅう"),                  # だいかさね（×）
        (r"徴さ", "ちょうさ"),                    # しるさ（×）
        (r"墓所", "ぼしょ"),                      # はかしょ（×）
        (r"留置", "りゅうち"),                    # とめおき（×）
        (r"預入", "あずけいれ"),                  # よにゅう（×）
        (r"時課税", "じかぜい"),                  # 国外転出（贈与）時課税 → ときかぜい（×）
        (r"終価", "しゅうか"),                    # おわりか（×）
        (r"切上", "きりあげ"),
    ],
    "hojin": [
        (r"(?<![一-龥])親法人", "おやほうじん"),  # しんほうじん（×）
    ],
    "shohi": [],
    "sozoku": [],
}


def fix(app, text):
    for pat, rep in FIX["all"] + FIX.get(app, []):
        text = re.sub(pat, rep, text)
    return text
